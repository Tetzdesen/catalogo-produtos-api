-- =============================================================================
-- Schema inicial do catálogo: a tabela de produtos.
-- =============================================================================
--
-- Por que este arquivo existe, e não 'ddl-auto: update'?
--
-- O Hibernate consegue criar tabelas sozinho a partir das entidades, mas o
-- resultado não fica versionado em lugar nenhum: o schema vira efeito colateral
-- do código, e ninguém consegue revisar em um pull request o que mudou no banco.
-- Com o Flyway, cada alteração de schema é um arquivo SQL numerado, aplicado uma
-- única vez e registrado na tabela 'flyway_schema_history'.
--
-- Uma vez aplicada, a migração NÃO pode ser editada — o Flyway guarda um
-- checksum e recusa a subida se o conteúdo mudar. Alterações futuras entram
-- como V2, V3, e assim por diante.

-- 'unaccent' remove acentos de um texto: unaccent('Café') = 'Cafe'. É o que
-- permite a busca por nome encontrar "Café" quando o cliente digita "cafe".
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE produto (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- SKU: a identidade externa do produto, aquela que o cliente da API usa.
    -- Diferente do 'id', que é interno e gerado pelo banco.
    sku       VARCHAR(40)   NOT NULL,
    nome      VARCHAR(120)  NOT NULL,
    descricao VARCHAR(500),
    -- NUMERIC e nunca DOUBLE: ponto flutuante binário não representa 0,10 de
    -- forma exata e acumula erro a cada operação. Dinheiro não perdoa isso.
    preco     NUMERIC(12,2) NOT NULL,
    ativo     BOOLEAN       NOT NULL DEFAULT TRUE,
    -- Última linha de defesa das regras: a API já valida, mas o banco também
    -- recusa SKU repetido e preço zerado, mesmo vindo de um UPDATE manual.
    CONSTRAINT uk_produto_sku UNIQUE (sku),
    CONSTRAINT ck_produto_preco_positivo CHECK (preco > 0)
);

-- Sem índice em 'nome' de propósito: a busca é por trecho ('%cafe%') sobre
-- unaccent(nome), e um índice B-tree comum não serve para esse tipo de consulta.
-- Para um catálogo pequeno, ler a tabela inteira é rápido; com tabelas grandes,
-- o caminho é um índice GIN com a extensão pg_trgm.
