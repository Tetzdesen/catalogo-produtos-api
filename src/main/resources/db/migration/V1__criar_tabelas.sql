-- Schema inicial do catálogo e do controle de estoque.
--
-- O SQL é deliberadamente portável entre PostgreSQL e H2 (modo PostgreSQL),
-- porque esta mesma migração roda na suíte de testes. Nada de tipos ou funções
-- exclusivos de um dos dois bancos.

CREATE TABLE categoria (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(60) NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

-- A unicidade sem distinção de caixa é garantida pelo service (existsByNomeIgnoreCase).
-- Aqui fica apenas a trava exata: índice funcional sobre LOWER(nome) resolveria no
-- PostgreSQL, mas não é suportado pelo H2 e quebraria os testes (ver README, decisão 9).

CREATE TABLE produto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           VARCHAR(40)   NOT NULL,
    nome          VARCHAR(120)  NOT NULL,
    descricao     VARCHAR(500),
    preco         NUMERIC(12,2) NOT NULL,
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    saldo_estoque INTEGER       NOT NULL DEFAULT 0,
    categoria_id  BIGINT        NOT NULL,
    CONSTRAINT uk_produto_sku UNIQUE (sku),
    CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    -- Última linha de defesa das invariantes: mesmo um UPDATE manual no banco
    -- não consegue deixar preço zerado nem saldo negativo.
    CONSTRAINT ck_produto_preco_positivo CHECK (preco > 0),
    CONSTRAINT ck_produto_saldo_nao_negativo CHECK (saldo_estoque >= 0)
);

-- Índices desenhados para os filtros da listagem de produtos.
CREATE INDEX ix_produto_categoria ON produto (categoria_id);
CREATE INDEX ix_produto_nome ON produto (nome);
CREATE INDEX ix_produto_ativo ON produto (ativo);
CREATE INDEX ix_produto_preco ON produto (preco);

CREATE TABLE movimentacao_estoque (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id       BIGINT       NOT NULL,
    tipo             VARCHAR(10)  NOT NULL,
    -- 'quantidade' é o valor informado na requisição: unidades para ENTRADA/SAIDA,
    -- saldo-alvo para AJUSTE. 'diferenca' é o que de fato foi somado ao saldo
    -- (negativo em saídas e em ajustes para baixo). Manter os dois separados deixa
    -- o histórico legível sem exigir interpretação por tipo.
    quantidade       INTEGER      NOT NULL,
    diferenca        INTEGER      NOT NULL,
    saldo_resultante INTEGER      NOT NULL,
    motivo           VARCHAR(120) NOT NULL,
    data_hora        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_movimentacao_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_movimentacao_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA', 'AJUSTE')),
    CONSTRAINT ck_movimentacao_quantidade CHECK (
        (tipo IN ('ENTRADA', 'SAIDA') AND quantidade > 0) OR (tipo = 'AJUSTE' AND quantidade >= 0)
    ),
    CONSTRAINT ck_movimentacao_saldo_nao_negativo CHECK (saldo_resultante >= 0)
);

-- Consulta principal do histórico: por produto, da mais recente para a mais antiga.
CREATE INDEX ix_movimentacao_produto_data ON movimentacao_estoque (produto_id, data_hora DESC);
-- Mesma consulta com o filtro opcional de tipo.
CREATE INDEX ix_movimentacao_produto_tipo ON movimentacao_estoque (produto_id, tipo);
